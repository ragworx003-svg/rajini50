-- Admin dashboard, Tamil book price, and privacy-light visitor engagement metrics.
-- Apply in Supabase SQL Editor after the book_orders migration.

alter table public.book_orders
  add column if not exists unit_price_paise bigint check (unit_price_paise is null or unit_price_paise > 0),
  add column if not exists total_price_paise bigint check (total_price_paise is null or total_price_paise > 0);

create table if not exists public.book_prices (
  book_id text primary key check (book_id = 'tamil'),
  currency text not null default 'INR' check (currency = 'INR'),
  price_paise bigint check (price_paise is null or price_paise > 0),
  updated_at timestamptz not null default now()
);

insert into public.book_prices (book_id, currency, price_paise)
values ('tamil', 'INR', null)
on conflict (book_id) do nothing;

alter table public.book_prices enable row level security;
revoke all on table public.book_prices from anon, authenticated;
grant select on table public.book_prices to anon;
drop policy if exists "Public can read Tamil book price" on public.book_prices;
create policy "Public can read Tamil book price"
  on public.book_prices for select to anon using (book_id = 'tamil');

create table if not exists public.site_session_events (
  id bigint generated by default as identity primary key,
  visitor_id uuid not null,
  session_id uuid not null,
  active_seconds smallint not null check (active_seconds between 1 and 60),
  created_at timestamptz not null default now()
);

create index if not exists site_session_events_created_at_idx
  on public.site_session_events (created_at desc);
create index if not exists site_session_events_visitor_id_idx
  on public.site_session_events (visitor_id, created_at desc);

alter table public.site_session_events enable row level security;
revoke all on table public.site_session_events from anon, authenticated;
grant insert (visitor_id, session_id, active_seconds) on table public.site_session_events to anon;
grant usage, select on sequence public.site_session_events_id_seq to anon;
drop policy if exists "Visitors can record active time" on public.site_session_events;
create policy "Visitors can record active time"
  on public.site_session_events for insert to anon
  with check (active_seconds between 1 and 60);

-- Always snapshot the current server-controlled price, even though order creation
-- is allowed from the public browser client.
create or replace function public.set_tamil_order_price()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_price bigint;
begin
  select price_paise into current_price
    from public.book_prices
    where book_id = 'tamil';
  if current_price is null then
    raise exception 'Tamil book price has not been set';
  end if;
  new.unit_price_paise := current_price;
  new.total_price_paise := current_price * new.quantity;
  return new;
end;
$$;
revoke all on function public.set_tamil_order_price() from public, anon, authenticated;
drop trigger if exists set_tamil_order_price_before_insert on public.book_orders;
create trigger set_tamil_order_price_before_insert
  before insert on public.book_orders
  for each row execute function public.set_tamil_order_price();

-- Restrict public order inserts to checkout fields. The trigger controls price
-- snapshots and clients cannot choose the order id or creation timestamp.
revoke insert on table public.book_orders from anon, authenticated;
grant insert (
  order_reference, edition, customer_name, email, phone,
  shipping_address, shipping_address2, city, state, postal_code, country,
  quantity, delivery_notes, unit_price_paise, total_price_paise, status
) on public.book_orders to anon;
