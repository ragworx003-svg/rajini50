-- Tamil book orders submitted by the public storefront.
-- Apply this migration in the Supabase SQL Editor before enabling checkout.
create table if not exists public.book_orders (
  id bigint generated by default as identity primary key,
  order_reference text not null unique,
  edition text not null check (edition = 'tamil'),
  customer_name text not null check (char_length(customer_name) between 1 and 100),
  email text not null check (char_length(email) between 3 and 160),
  phone text not null check (char_length(phone) between 8 and 30),
  shipping_address text not null check (char_length(shipping_address) between 1 and 180),
  shipping_address2 text check (shipping_address2 is null or char_length(shipping_address2) <= 180),
  city text not null check (char_length(city) between 1 and 100),
  state text not null check (char_length(state) between 1 and 100),
  postal_code text not null check (char_length(postal_code) between 4 and 12),
  country text not null check (char_length(country) between 1 and 80),
  quantity integer not null check (quantity between 1 and 20),
  delivery_notes text check (delivery_notes is null or char_length(delivery_notes) <= 300),
  status text not null default 'pending_payment'
    check (status in ('pending_payment', 'paid', 'cancelled', 'fulfilled')),
  created_at timestamptz not null default now()
);

alter table public.book_orders enable row level security;

-- Public customers can create orders, but cannot read or modify anyone's order.
revoke all on table public.book_orders from anon, authenticated;
grant insert on table public.book_orders to anon;
grant usage, select on sequence public.book_orders_id_seq to anon;
drop policy if exists "Public can submit book orders" on public.book_orders;
create policy "Public can submit book orders"
  on public.book_orders
  for insert
  to anon
  with check (
    edition = 'tamil'
    and status = 'pending_payment'
    and quantity between 1 and 20
  );
